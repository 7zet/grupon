package merchant

import (
	"fmt"
	"strings"
)

// DemoDocumentPrefix marks storage keys of placeholder documents created by the demo seed. No file is
// stored for them; Open serves DemoDocument instead, so they work on any host.
const DemoDocumentPrefix = "demo-"

// DemoDocumentKey returns the storage key of the placeholder price proof of one demo business.
func DemoDocumentKey(slug string) string { return DemoDocumentPrefix + "price-proof-" + slug + ".pdf" }

// DemoDocument returns a one-page PDF that says plainly it is a demo placeholder, not a real document.
func DemoDocument() []byte {
	stream := "BT /F1 20 Tf 60 740 Td (DEMO - placeholder price proof) Tj 0 -30 Td /F1 12 Tf (Generated by the demo seed. Not a real document.) Tj ET"
	objects := []string{
		"<< /Type /Catalog /Pages 2 0 R >>",
		"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
		"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
		fmt.Sprintf("<< /Length %d >>\nstream\n%s\nendstream", len(stream), stream),
		"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
	}
	var out strings.Builder
	out.WriteString("%PDF-1.4\n")
	offsets := make([]int, len(objects))
	for i, body := range objects {
		offsets[i] = out.Len()
		fmt.Fprintf(&out, "%d 0 obj\n%s\nendobj\n", i+1, body)
	}
	xref := out.Len()
	fmt.Fprintf(&out, "xref\n0 %d\n0000000000 65535 f \n", len(objects)+1)
	for _, offset := range offsets {
		fmt.Fprintf(&out, "%010d 00000 n \n", offset)
	}
	fmt.Fprintf(&out, "trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n", len(objects)+1, xref)
	return []byte(out.String())
}

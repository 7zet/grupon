import { chromium } from '@playwright/test';
const API = 'http://127.0.0.1:8080/api/v1';
const b = await chromium.launch({ channel: 'msedge' });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
const phone = '+998900000003';
const { dev_code } = await (await ctx.request.post(`${API}/auth/phone/code`, { data: { phone } })).json();
await ctx.request.post(`${API}/auth/phone/verify`, { data: { phone, code: dev_code } });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:3000/uz/merchant/redeem', { waitUntil: 'load' });
await p.waitForTimeout(4000);
console.log(await p.evaluate(() => [...document.querySelectorAll('body *')].filter((e) => e.getBoundingClientRect().right > window.innerWidth + 1).slice(0, 8).map((e) => e.tagName + '.' + String(e.className).slice(0, 80) + ' ' + Math.round(e.getBoundingClientRect().right))));
await b.close();
